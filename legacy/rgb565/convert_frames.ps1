# Extract ALL GIF frames and their original delays -> RGB565 C arrays.
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing

$assetDir = Join-Path $PSScriptRoot 'assets'
$outPath  = Join-Path $PSScriptRoot 'whale_frames.h'

$order = @("idle", "happy", "sleepy", "think", "alert")
$map = @{ idle = "idle.gif"; happy = "happy.gif"; sleepy = "sleepy.gif"; think = "think.gif"; alert = "alert.gif" }
$counts = @{}

$W = 96
$H = 96
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by convert_frames.ps1. Do not edit by hand.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('#include <stdint.h>')
[void]$sb.AppendLine('#include <pgmspace.h>')

# PowerShell preserves Byte for shifts: widen BEFORE shifting or red is lost.
function ConvertTo-Rgb565([int]$Red, [int]$Green, [int]$Blue) {
    return (($Red -shr 3) -shl 11) -bor (($Green -shr 2) -shl 5) -bor ($Blue -shr 3)
}
if ((ConvertTo-Rgb565 255 255 255) -ne 0xFFFF -or
    (ConvertTo-Rgb565 255 0 0) -ne 0xF800 -or
    (ConvertTo-Rgb565 0 255 0) -ne 0x07E0 -or
    (ConvertTo-Rgb565 0 0 255) -ne 0x001F) {
    throw 'RGB565 color conversion failed its primary-color checks.'
}

foreach ($name in $order) {
    $path = Join-Path $assetDir $map[$name]
    $img = [System.Drawing.Image]::FromFile($path)
    $guid = $img.FrameDimensionsList[0]
    $dim = [System.Drawing.Imaging.FrameDimension]::new($guid)
    $count = $img.GetFrameCount($dim)
    $counts[$name] = $count
    $delayBytes = if ($img.PropertyIdList -contains 0x5100) { $img.GetPropertyItem(0x5100).Value } else { $null }
    $delays = for ($i = 0; $i -lt $count; $i++) {
        $delay = if ($delayBytes -and $delayBytes.Length -ge ($i + 1) * 4) {
            [int][BitConverter]::ToUInt32($delayBytes, $i * 4) * 10
        } else { 100 }
        if ($delay -le 0) { $delay = 100 }
        if ($delay -gt 65535) { throw "Frame delay too large: $name frame $i" }
        $delay
    }
    Write-Host "$name : $count frames, $(($delays | Measure-Object -Sum).Sum) ms (src $($img.Width)x$($img.Height))"

    [void]$sb.AppendLine("const uint16_t whale_$name[$($count * $W * $H)] PROGMEM = {")

    $rect = New-Object System.Drawing.Rectangle(0, 0, $W, $H)

    for ($i = 0; $i -lt $count; $i++) {
        [void]$img.SelectActiveFrame($dim, $i)
        $bmp = New-Object System.Drawing.Bitmap($W, $H)
        $g = [System.Drawing.Graphics]::FromImage($bmp)
        $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
        $srcSize = [Math]::Min($img.Width, $img.Height)
        $srcX = [int](($img.Width - $srcSize) / 2)
        $srcY = [int](($img.Height - $srcSize) / 2)
        $srcRect = New-Object System.Drawing.Rectangle($srcX, $srcY, $srcSize, $srcSize)
        $dstRect = New-Object System.Drawing.Rectangle(0, 0, $W, $H)
        $g.DrawImage($img, $dstRect, $srcRect, [System.Drawing.GraphicsUnit]::Pixel)
        $g.Dispose()

        $bd = $bmp.LockBits($rect, [System.Drawing.Imaging.ImageLockMode]::ReadOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
        $stride = $bd.Stride
        $bytes = New-Object byte[] ($stride * $H)
        [System.Runtime.InteropServices.Marshal]::Copy($bd.Scan0, $bytes, 0, $bytes.Length)
        $bmp.UnlockBits($bd)
        $bmp.Dispose()

        $lineSb = New-Object System.Text.StringBuilder
        for ($y = 0; $y -lt $H; $y++) {
            for ($x = 0; $x -lt $W; $x++) {
                $idx = $y * $stride + $x * 4
                $b = $bytes[$idx]; $gg = $bytes[$idx+1]; $r = $bytes[$idx+2]; $a = $bytes[$idx+3]
                if ($a -lt 128) {
                    [void]$lineSb.Append("0x0000,")
                } else {
                    $r5 = [int]$r -shr 3
                    $g6 = [int]$gg -shr 2
                    $b5 = [int]$b -shr 3
                    $v = ($r5 -shl 11) -bor ($g6 -shl 5) -bor $b5
                    [void]$lineSb.Append(("0x{0:X4}," -f $v))
                }
            }
            [void]$lineSb.Append("`n")
        }
        [void]$sb.Append($lineSb.ToString())
    }
    [void]$sb.AppendLine("};")
    [void]$sb.AppendLine("const uint16_t whale_${name}_delays[$count] PROGMEM = { $($delays -join ',') };")
    $img.Dispose()
}

[void]$sb.AppendLine("#define FR_IDLE  $($counts['idle'])")
[void]$sb.AppendLine("#define FR_HAPPY $($counts['happy'])")
[void]$sb.AppendLine("#define FR_SLEEPY $($counts['sleepy'])")
[void]$sb.AppendLine("#define FR_THINK $($counts['think'])")
[void]$sb.AppendLine("#define FR_ALERT $($counts['alert'])")
[void]$sb.AppendLine("#define PET_W $W")
[void]$sb.AppendLine("#define PET_H $H")

[System.IO.File]::WriteAllText($outPath, $sb.ToString())
$size = (Get-Item $outPath).Length
Write-Host "saved: $outPath ($([int]($size/1KB)) KB)"
